"""Render the Ongkara (assets/ongkara.png: the glyph, white on black, as Noto Sans Balinese draws it) to a
C header for HOME: the glyph and its glow, coverage 0..15, rows top to bottom, 2 pixels per byte (high
nibble first), as the font's glyphs and the logo.

  ONG_*       the glyph, ONG_H pixels tall
  ONG_GLOW_*  the glow: the glyph blurred, ONG_PAD pixels wider on every side (drawn under it, tinted
              as bright as the music swells)

  tools/gen_ongkara.py build/gen/ongkara.h
"""
import sys
from pathlib import Path

from PIL import Image, ImageFilter

SRC = Path(__file__).resolve().parents[1] / "assets" / "ongkara.png"
H = 70          # the glyph's height on HOME (its disc is 96 across)
PAD = 14        # the glow's reach past it
BLUR = 6.0


def nibbles(im, name):
    w, h = im.size
    px = im.load()
    bpr = (w + 1) // 2
    data = bytearray()
    for y in range(h):
        row = [min(15, (px[x, y] + 8) // 17) for x in range(w)] + [0]
        data += bytes((row[x] << 4) | row[x + 1] for x in range(0, bpr * 2, 2))
    lines = [f"#define {name}_W {w}", f"#define {name}_H {h}",
             f"static const uint8_t {name}_PX[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    return lines, f"{w} x {h}"


def main(out):
    im = Image.open(SRC).convert("L")
    im = im.crop(im.getbbox())
    w = round(im.width * H / im.height)
    glyph = im.resize((w, H), Image.LANCZOS)
    glow = Image.new("L", (w + 2 * PAD, H + 2 * PAD), 0)
    glow.paste(glyph, (PAD, PAD))
    glow = glow.filter(ImageFilter.GaussianBlur(BLUR))
    peak = max(glow.getextrema()[1], 1)
    glow = glow.point(lambda v: min(255, v * 255 // peak))   # (its brightest at full: the tint sets how bright)
    lines = ["/* generated by tools/gen_ongkara.py from assets/ongkara.png (Noto Sans Balinese, SIL OFL 1.1) */",
             f"#define ONG_PAD {PAD}"]
    said = []
    for name, img in (("ONG", glyph), ("ONG_GLOW", glow)):
        l, s = nibbles(img, name)
        lines += l
        said.append(s)
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"gen_ongkara: {'; '.join(said)}")


if __name__ == "__main__":
    main(sys.argv[1])
